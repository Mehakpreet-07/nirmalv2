function mountHome() {
  const featured = document.getElementById("home-featured");
  if (featured) {
    const ids = ["abbotsford-plaza", "radley-surrey", "residential-homes"];
    featured.innerHTML = ids
      .map(id => siteData.projects.find(project => project.id === id))
      .filter(Boolean)
      .map(projectCard)
      .join("");
  }

  const qualifications = document.getElementById("qualification-list");
  if (qualifications) {
    qualifications.innerHTML = siteData.qualifications
      .map(item => `<div class="simple-list__item">${item}</div>`)
      .join("");
  }
}

function mountProjects() {
  ["commercial", "multifamily", "residential"].forEach(category => {
    const root = document.getElementById(`${category}-projects`);
    if (!root) return;

    root.innerHTML = siteData.projects
      .filter(project => project.category === category)
      .map(projectCard)
      .join("");
  });
}

function mountProjectDetail() {
  const root = document.getElementById("project-detail-root");
  if (!root) return;

  const id = new URLSearchParams(window.location.search).get("id");
  const project = siteData.projects.find(item => item.id === id);

  if (!project) {
    root.innerHTML = `
      <section class="section">
        <div class="container">
          <h1>Project not found.</h1>
          <a class="text-link" href="projects.html">Back to Projects →</a>
        </div>
      </section>
    `;
    return;
  }

  document.title = `${project.title} | Master Craftsman Construction Ltd.`;

  document.getElementById("project-category").textContent = project.category;
  document.getElementById("project-name").textContent = project.title;
  document.getElementById("project-hero-image").style.backgroundImage = `url("${project.images[0]}")`;

  // User requested only: role, name, size, construction, category.
  const info = [
    ["Role", project.role],
    ["Name", project.title],
    ["Size", project.size],
    ["Construction", project.construction],
    ["Category", project.category]
  ];

  document.getElementById("project-info-grid").innerHTML = info
    .map(([label, value]) => `
      <div class="project-info-item">
        <span>${label}</span>
        <strong>${value}</strong>
      </div>
    `).join("");

  document.getElementById("project-gallery").innerHTML = project.images
    .map((src, index) => `
      <figure class="reveal">
        <img src="${src}" alt="${project.title} placeholder project image ${index + 1}" loading="${index === 0 ? "eager" : "lazy"}">
      </figure>
    `).join("");
}

function mountContactForm() {
  const form = document.getElementById("contact-form");
  if (!form) return;

  const status = document.getElementById("form-status");

  function setError(field, message) {
    const wrapper = field.closest(".field");
    wrapper.classList.toggle("invalid", Boolean(message));
    wrapper.querySelector(".error").textContent = message;
  }

  function validate() {
    let valid = true;
    ["name", "email", "projectType", "message"].forEach(name => {
      const field = form.elements[name];
      if (!field.value.trim()) {
        setError(field, "This field is required.");
        valid = false;
      } else {
        setError(field, "");
      }
    });

    const email = form.elements.email;
    if (email.value.trim() && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.value.trim())) {
      setError(email, "Enter a valid email address.");
      valid = false;
    }

    const phone = form.elements.phone;
    if (phone.value.trim() && !/^[0-9+().\-\s]{7,20}$/.test(phone.value.trim())) {
      setError(phone, "Enter a valid phone number.");
      valid = false;
    } else {
      setError(phone, "");
    }

    return valid;
  }

  form.addEventListener("submit", event => {
    event.preventDefault();
    status.textContent = "";
    status.className = "form-status";

    if (!validate()) {
      status.textContent = "Please review the highlighted fields.";
      status.classList.add("failure");
      return;
    }

    status.textContent = "Thank you. The form is ready to connect to an email or backend service when the website is published.";
    status.classList.add("success");
    form.reset();
  });
}

function mountRevealAnimations() {
  const elements = document.querySelectorAll(".reveal");

  if (!("IntersectionObserver" in window)) {
    elements.forEach(el => el.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });

  elements.forEach(el => observer.observe(el));
}

document.addEventListener("DOMContentLoaded", () => {
  mountSharedLayout();
  mountHome();
  mountProjects();
  mountProjectDetail();
  mountContactForm();
  requestAnimationFrame(mountRevealAnimations);
});
